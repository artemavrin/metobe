// Что человек просит поменять в каждой из трёх задач (/task-results) и что модель предлагает в ответ — карточкой «было →
// стало» (D28): применяет человек, не модель. Поле ввода уже заполнено этой просьбой — её можно отправить или написать
// свою: прототип на любую ответит тем же предложением.

export interface Field {
  label: string;
  value: string;
}

export interface Change {
  label: string;
  before: string;
  after: string;
  /** Что в `after` новое — выделяется. Нет — новое всё значение. */
  added?: string;
}

export interface Edit {
  ask: string;
  changes: Change[];
  /** Что из задачи остаётся как было. */
  same: string;
  /** Что изменится в работе задачи — факт, не обещание. */
  note?: string;
  /** Строка после применения: «Изменена 30 ноя: …». */
  summary: string;
  /** Расписание после изменения, если оно меняется, и ближайший запуск по нему. */
  schedule?: string;
  next?: string;
}

