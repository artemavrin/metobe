import type { Outcome } from "../agents/data";

// P12 · входящие агентов (§16.4): одна лента того, что агенты прислали. Четыре вида по ambient agents LangChain:
// Notify — «вот сводка», Question — агенту нужен ответ или подключение, Alert — сбой или пауза, Review —
// подтвердить действие. «Ничего нового» сюда не попадает (`if_new`). Те же агенты и запуски, что в P13.

export type Kind = "notify" | "question" | "alert" | "review";

export interface Item {
  id: string;
  kind: Kind;
  agentId: string;
  /** Запуск, из которого пришло, — в прототипе агентов. */
  runId: string;
  at: string;
  /** Одна строка: о чём. */
  title: string;
  /** 1–3 строки сводки. */
  text: string;
  read: boolean;
  outcome?: Outcome;
  report?: string;
  letter?: { to: string; subject: string; body: string };
  /** Что сделать, если пункт ждёт человека. */
  action?: string;
}

