// P13, раунд 3, вариант «Страница»: агент не пишет ленту итогов, а держит одну страницу — что сейчас — и при каждом
// запуске переписывает её. Новое с прошлого раза помечено, ушедшее зачёркнуто, изменившееся — с «было». История —
// версии страницы. Для агентов, которые следят за состоянием (остатки, счета, цены), это и есть ответ на «что там».

export type Mark = "new" | "gone" | "changed";

export interface Line {
  text: string;
  /** Подробность справа: сумма, количество, срок. */
  aside?: string;
  mark?: Mark;
  /** Как было до этого запуска — у изменившегося. */
  was?: string;
}

export interface AgentPage {
  /** Одна строка: что сейчас главное. */
  headline: string;
  /** С каким запуском сравнивали. */
  since: string;
  updated: string;
  /** Страница устарела: агент стоит, данные на эту дату. */
  stale?: string;
  sections: { title: string; lines: Line[] }[];
  versions: string[];
}

