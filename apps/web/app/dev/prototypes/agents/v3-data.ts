/** Сколько изменилось с прошлого раза: «2 новых · 1 ушло». */
export const changesOf = (page: AgentPage) => {
  const lines = page.sections.flatMap((s) => s.lines);
  const n = (m: Mark) => lines.filter((l) => l.mark === m).length;
  return { changed: n("changed"), gone: n("gone"), fresh: n("new") };
};
