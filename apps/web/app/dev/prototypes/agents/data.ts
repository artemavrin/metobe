import type { Step, StepState } from "../activity/data";

// P13 · агенты одного человека: что каждый делает, когда, чем, как прошли последние запуски. Сейчас — пятница,
// 30 октября, 10:42. Шесть агентов в шести состояниях: идёт запуск, ждёт подтверждения письма, ждёт подключения,
// остановлен после пяти сбоев подряд, на паузе по воле владельца, просто ждёт расписания. Шаги запусков — те же,
// что в ленте чата (P4): поиск, чтение страницы, вызов тула сервера, письмо.

export const NOW = "2026-10-30T10:42";

export type Outcome = "done" | "nothing" | "attention" | "failed";
export type Trigger = "schedule" | "manual" | "test";
export type Currency = "USD" | "RUB";

/** Где агент сейчас: работает, ждёт человека, стоит (после сбоев или по воле владельца), ждёт расписания. */
export type AgentState = "running" | "waiting" | "failed" | "paused" | "idle";

export interface RunStep extends Step {
  state: StepState;
}

export interface Run {
  id: string;
  /** Местное время начала, `YYYY-MM-DDTHH:mm`. */
  at: string;
  trigger: Trigger;
  /** Исход закончившегося запуска; у идущего и ждущего его ещё нет. */
  outcome?: Outcome;
  live?: "running" | "waiting";
  ms: number;
  cost: number;
  currency: Currency;
  tokens: number;
  version: number;
  /** Что запуск сообщил, одной-двумя строками (`report.summary`). */
  summary: string;
  /** Полный отчёт — то, что приходит во входящие и открывается в чате запуска. */
  report?: string;
  steps?: RunStep[];
  /** Попытки, если запуск повторяли. */
  attempts?: { at: string; error: string }[];
}

export interface Agent {
  id: string;
  name: string;
  /** Одна строка: что агент делает. */
  about: string;
  /** Расписание словами и сам cron — его предложила модель, даты считает сервер. */
  schedule: string;
  cron: string;
  /** Следующий запуск; у остановленного его нет. */
  next?: string;
  state: AgentState;
  /** Почему агент ждёт или стоит — и что с этим сделать. */
  reason?: { text: string; action?: string; since?: string };
  /** Идущий запуск: шаг из скольких и что сейчас делает. */
  progress?: { step: number; of: number; doing: string };
  tools: string[];
  notify: string;
  model: string;
  instructions: string;
  version: number;
  runs: Run[];
}

