/** Stems that end in a consonant: a name that loses a vowel when declined, or a short name like «Макс». */
const HARD: [stem: string, full: string[]][] = [
  ["павл", ["павел"]],
  ["льв", ["лев"]],
  ["макс", ["максим"]],
  ["стас", ["станислав"]],
  ["влад", ["владислав", "владимир"]],
  ["вадик", ["вадим"]],
  ["эдик", ["эдуард"]],
  ["костик", ["константин"]],
];

const fullOf = (
  word: string,
  list: [string, string[]][],
  endings: Set<string>
) =>
  list.flatMap(([stem, full]) =>
    word.startsWith(stem) && endings.has(word.slice(stem.length)) ? full : []
  );

/**
 * The full names a word may stand for — «оле» → [ольга], «павлу» → [павел], «саша» → [александр, александра]; empty
 * for a word that is not a short or vowel-losing form. The word comes as `wordsOf` gives it: lower case, «ё» as «е».
 */
export const fullNames = (word: string) => [
  ...new Set([
    ...fullOf(word, SHORT, SHORT_ENDINGS),
    ...fullOf(word, HARD, HARD_ENDINGS),
  ]),
];
